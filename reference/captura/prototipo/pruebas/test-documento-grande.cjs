const { chromium } = require('playwright-core');
const fs = require('fs'), path = require('path');
const DS = '<SANDBOX>/ds/out/project/components/lib/';
const DOCX = require('child_process').execSync('npm root -g').toString().trim() + '/docx/dist/index.iife.js';
const papel = process.argv[2] || 'Carta';
const GRANDE = fs.readFileSync(path.join(__dirname, 'out/grande.json'), 'utf8');
const FAKE = `window.claude = { use: async n => n === 'downloads' ? { save: async r => { window.__d = (window.__d || []).concat([r.filename]); window.__datos = r.data; return { status: 'saved' }; } } : null };
try { if (!localStorage.getItem('kaze-captura:procesos:v1')) { const g = ${GRANDE}; localStorage.setItem('kaze-captura:procesos:v1', JSON.stringify({ [g.id]: g })); } } catch (e) {}`;
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  await ctx.route('https://cdnjs.cloudflare.com/**', r => r.fulfill({ contentType: 'text/javascript', body: fs.readFileSync(DS + (r.request().url().includes('react-dom') ? 'react-dom.production.min.js' : 'react.production.min.js'), 'utf8') }));
  await ctx.route('https://cdn.jsdelivr.net/**', r => { const u = r.request().url(); const f = u.includes('docx') ? DOCX : path.join(__dirname, 'package/dist/bpmn-modeler.production.min.js'); r.fulfill({ contentType: 'text/javascript', body: fs.readFileSync(f, 'utf8') }); });
  await ctx.route(u => u.hostname.startsWith('fonts.'), r => r.fulfill({ contentType: 'text/css', body: '' }));
  await ctx.addInitScript(FAKE);
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()); });
  await p.goto('file://' + path.join(__dirname, 'out/test.html')); await p.waitForSelector('.tabla-procesos tbody tr');
  await p.click('.enlace-fila:has-text("Proceso grande")'); await p.waitForSelector('.tabs');
  await p.click('.kz-head button:has-text("Exportar documento")'); await p.waitForSelector('.modal');
  if (papel === 'A4') await p.click('.doc-op button:has-text("A4")');
  console.log('por fase:', await p.$eval('.doc-check input', e => e.checked), '·', await p.$eval('.doc-check .campo__ayuda', e => e.textContent));
  const t0 = Date.now();
  await p.click('.modal__pie button:has-text("Descargar Word")');
  await p.waitForSelector('.doc-ok', { timeout: 60000 });
  console.log('tiempo:', Date.now() - t0, 'ms');
  const b64 = await p.evaluate(async () => { const d = window.__datos; const buf = await d.arrayBuffer(); const u = new Uint8Array(buf); let s = ''; for (let i = 0; i < u.length; i += 0x8000) s += String.fromCharCode.apply(null, u.subarray(i, i + 0x8000)); return btoa(s); });
  fs.writeFileSync(path.join(__dirname, 'out/doc-grande-' + papel + '.docx'), Buffer.from(b64, 'base64'));
  console.log('tamaño:', fs.statSync(path.join(__dirname, 'out/doc-grande-' + papel + '.docx')).size);
  console.log('ERRORES:', errs.length ? errs : 'ninguno');
  await b.close();
})().catch(e => { console.error('FALLO', e.stack); process.exit(1); });
